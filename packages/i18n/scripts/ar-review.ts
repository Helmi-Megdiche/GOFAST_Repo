/**
 * Builds packages/i18n/AR-REVIEW.md: every Arabic key, next to its French source,
 * for the native-speaker review required by CLAUDE.md.
 * Pure functions, no imports: used by gen-ar-review.ts and by the drift test.
 */

export type Catalog = { [key: string]: string | Catalog };

export function flatten(catalog: Catalog, prefix = ""): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(catalog)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === "string") out[path] = value;
    else Object.assign(out, flatten(value, path));
  }
  return out;
}

const HEADER = `# Arabic review

Every Arabic string in \`src/messages/ar.json\`, with its French source. All of them need a
native-speaker review before release (CLAUDE.md).

- Generated by \`pnpm --filter @fastgo/i18n ar-review\`. Do not edit the first three columns.
- Reviewer: tick the last column (\`[x]\`) and add a note after it if you changed the wording
  in \`ar.json\`.
- Adding an Arabic key without running the script fails the i18n test.

| Key | Arabic | French (source) | Reviewed |
| --- | --- | --- | --- |
`;

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

/** Keep the "Reviewed" cell of rows that already exist. */
function reviewedByKey(previous: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const line of previous.split("\n")) {
    const match = /^\| `([^`]+)` \|.*\| ([^|]*) \|$/.exec(line);
    if (match?.[1] && match[2] !== undefined) map.set(match[1], match[2]);
  }
  return map;
}

export function renderArReview(ar: Catalog, fr: Catalog, previous = ""): string {
  const arFlat = flatten(ar);
  const frFlat = flatten(fr);
  const reviewed = reviewedByKey(previous);

  const rows = Object.keys(arFlat)
    .sort()
    .map((key) => {
      const status = reviewed.get(key) ?? "[ ]";
      return `| \`${key}\` | ${cell(arFlat[key] ?? "")} | ${cell(frFlat[key] ?? "")} | ${status} |`;
    });

  return `${HEADER}${rows.join("\n")}\n`;
}
